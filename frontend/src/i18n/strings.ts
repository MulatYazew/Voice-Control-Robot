export type Key = keyof typeof S;
export const LangCtx = createContext<Lang>("it");
export function useT() {
  const lang = useContext(LangCtx);
  return (k: Key) => S[k][lang === "it" ? 0 : 1];
}
export function storedLang(): Lang {
  try { return (localStorage.getItem("voce.lang") as Lang) || "it"; } catch { return "it"; }
}
export function storeLang(l: Lang) {
  try { localStorage.setItem("voce.lang", l); } catch { /* private mode */ }
}
